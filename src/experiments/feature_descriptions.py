"""
Feature/Column Descriptions for Datasets

Provides brief, informative descriptions for each feature/column in each dataset.
These descriptions help LLMs understand the semantic meaning of features during:
- Path Explorer: Scoring tables for join relevance
- Feature Selector: Ranking features by predictive importance
"""

# Whether a dataset's column names or descriptions carry semantic signal for a language model.
# False: both are cryptic (e.g. V1-V54 with "Feature N" descriptions); the Path Explorer then scores paths by
# statistics only (S_sem = 0) and the Feature Selector ranks by statistics only.
# True: names or descriptions give domain context. A property of the schema, not a tuned parameter.
SEMANTIC_SIGNAL_AVAILABLE = {
    'credit':    True,   # descriptive names + descriptions
    'steel':     True,   # cryptic names but informative descriptions
    'eyemove':   True,   # descriptive names + descriptions
    'jannis':    False,  # V1-V54 names + "Feature N" descriptions — fully cryptic
    'miniboone': False,  # ParticleID_N + "Particle detector measurement N" — fully cryptic
    'covertype': True,   # descriptive names + descriptions
    'fraud':     True,   # mix of cryptic V-series + descriptive fields
    'diabetes':  True,   # fully descriptive
    'poverty':   True,   # descriptive
    'air':       True,   # semi-cryptic names but descriptions explain them
    'northwind': True,   # fully descriptive
    'school':    True,   # fully descriptive
    'bioresponse': False,  # D1-D1776 names and no descriptions — fully cryptic
}


def describe(descriptions, name: str):
    """The description of a column, or None.

    Descriptions are keyed by the column's own name, while the pipeline sees qualified names: some data files
    prefix every column with its table ('Age.Age', '1.C8', 'base.Sex') and consolidated tables prefix it again
    ('table_2_5.checking_status'). The name is matched as given first, then with its leading qualifiers removed one
    at a time, so 'table_2_5.checking_status' finds 'checking_status'.
    """
    if not descriptions:
        return None
    while True:
        if name in descriptions:
            return descriptions[name]
        if "." not in name:
            return None
        name = name.split(".", 1)[1]


def has_semantic_signal(dataset: str) -> bool:
    """
    Returns True if this dataset's schema provides meaningful semantic
    signal for LLM-based path exploration and feature selection.
    Returns True by default for unknown datasets (conservative).
    """
    return SEMANTIC_SIGNAL_AVAILABLE.get(dataset, True)


